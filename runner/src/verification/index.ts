import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { constants } from 'node:fs';
import { lstat, open, realpath } from 'node:fs/promises';
import { isAbsolute, join, relative, resolve, sep } from 'node:path';
import { performance } from 'node:perf_hooks';

export interface Acceptance {
  commands?: Array<{ argv: string[]; timeoutMs?: number }>;
  artifacts?: Array<{ path: string; sha256?: string }>;
}
type CheckStatus = 'passed' | 'failed' | 'cancelled';
export type VerificationCheck =
  | {
      kind: 'command';
      argv: string[];
      status: CheckStatus;
      durationMs: number;
      exitCode: number | null;
      signal: string | null;
      timedOut: boolean;
      stdout: string;
      stderr: string;
      stdoutTruncated: boolean;
      stderrTruncated: boolean;
      error?: string;
    }
  | {
      kind: 'artifact';
      path: string;
      status: CheckStatus;
      durationMs: number;
      sha256?: string;
      bytes?: number;
      error?: string;
    };
export interface VerificationResult {
  status: 'unverified' | 'passed' | 'failed' | 'cancelled';
  checks: VerificationCheck[];
  durationMs: number;
  reason?: string;
}
export interface VerificationInput {
  root: string;
  spec?: Acceptance;
  signal?: AbortSignal;
}
export interface AcceptanceVerifier {
  verify(input: VerificationInput): Promise<VerificationResult>;
}
export const VERIFICATION_LIMITS = Object.freeze({
  commands: 4,
  artifacts: 16,
  totalMs: 120_000,
  commandDefaultMs: 30_000,
  outputBytes: 16_384,
  artifactBytes: 64 * 1024 * 1024,
});
const protectedDirectories = new Set([
  '.logins',
  '.runner',
  '.ssh',
  '.aws',
  '.azure',
  '.kube',
  '.codex',
  '.claude',
  '.config',
  '.git',
]);
const protectedFiles = new Set([
  'auth.json',
  'credentials.json',
  '.credentials.json',
  'keys.json',
  '.runner-token',
  'application_default_credentials.json',
  'access_tokens.db',
  'credentials.db',
  'id_rsa',
  'id_ed25519',
  'id_ecdsa',
  'id_dsa',
  '.claude.json',
  'claude.json',
  '.npmrc',
  '.netrc',
]);
function pathCheck(path: unknown): asserts path is string {
  if (
    typeof path !== 'string' ||
    !path ||
    path.length > 1024 ||
    path.includes('\0') ||
    path.includes('\\') ||
    isAbsolute(path) ||
    path.split('/').some((part) => !part || part === '.' || part === '..')
  )
    throw new Error('Artifact path must be normalized and relative');
  const parts = path.toLowerCase().split('/');
  const file = parts.at(-1)!;
  if (
    parts.some((part) => protectedDirectories.has(part)) ||
    protectedFiles.has(file) ||
    file === '.env' ||
    (file.startsWith('.env.') && file !== '.env.example') ||
    /\.(?:pem|key)$/i.test(file)
  ) {
    throw new Error('Credential-bearing artifact paths are not allowed');
  }
}

/** Caller-owned checks, never generated by the executor. Not an OS sandbox:
 * commands run as the runner's user and can read that user's files. The limited
 * environment removes inherited provider/runner keys, not filesystem authority.
 * Same-user agents may modify checks/artifacts; a pass is only these observations.
 * No implicit shell, automatic judge, inference call, or verification retry.
 */
export function validateAcceptance(spec: Acceptance): Acceptance {
  if (!spec || typeof spec !== 'object' || Array.isArray(spec)) throw new Error('Invalid acceptance checks');
  if (
    spec.commands !== undefined &&
    (!Array.isArray(spec.commands) || spec.commands.length > VERIFICATION_LIMITS.commands)
  )
    throw new Error('At most four acceptance commands are allowed');
  if (
    spec.artifacts !== undefined &&
    (!Array.isArray(spec.artifacts) || spec.artifacts.length > VERIFICATION_LIMITS.artifacts)
  )
    throw new Error('At most sixteen acceptance artifacts are allowed');
  let duration = 0;
  const commands = spec.commands?.map((command) => {
    if (!command || !Array.isArray(command.argv) || !command.argv.length || command.argv.length > 32)
      throw new Error('Command argv must have 1-32 arguments');
    if (
      command.argv.some((arg) => typeof arg !== 'string' || arg.includes('\0')) ||
      !command.argv[0]?.trim() ||
      Buffer.byteLength(JSON.stringify(command.argv)) > 8192
    )
      throw new Error('Invalid or oversized command argv');
    const timeoutMs = command.timeoutMs ?? VERIFICATION_LIMITS.commandDefaultMs;
    if (!Number.isSafeInteger(timeoutMs) || timeoutMs <= 0 || timeoutMs > VERIFICATION_LIMITS.totalMs)
      throw new Error('Invalid command timeout');
    duration += timeoutMs;
    return { argv: [...command.argv], timeoutMs };
  });
  if (duration > VERIFICATION_LIMITS.totalMs)
    throw new Error('Acceptance command timeouts exceed the 120-second global limit');
  const artifacts = spec.artifacts?.map((artifact) => {
    if (!artifact) throw new Error('Invalid artifact check');
    pathCheck(artifact.path);
    if (artifact.sha256 !== undefined && !/^[a-fA-F0-9]{64}$/.test(artifact.sha256))
      throw new Error('Invalid artifact SHA256');
    return { path: artifact.path, ...(artifact.sha256 === undefined ? {} : { sha256: artifact.sha256.toLowerCase() }) };
  });
  return { ...(commands ? { commands } : {}), ...(artifacts ? { artifacts } : {}) };
}

function commandEnvironment(): Record<string, string> {
  const env: Record<string, string> = {};
  for (const key of ['PATH', 'LANG', 'HOME', 'TMPDIR'])
    if (process.env[key] !== undefined) env[key] = process.env[key]!;
  return env;
}
function utf8(buffer: Buffer): string {
  let value = buffer.toString('utf8');
  while (Buffer.byteLength(value) > VERIFICATION_LIMITS.outputBytes) value = value.slice(0, -1);
  return value;
}
async function commandCheck(
  root: string,
  command: { argv: string[]; timeoutMs?: number },
  signal: AbortSignal,
): Promise<VerificationCheck> {
  const started = performance.now();
  const base = {
    kind: 'command' as const,
    argv: command.argv,
    exitCode: null,
    signal: null,
    timedOut: false,
    stdout: '',
    stderr: '',
    stdoutTruncated: false,
    stderrTruncated: false,
  };
  if (signal.aborted) return { ...base, status: 'cancelled', durationMs: 0 };
  if (process.platform === 'win32')
    return {
      ...base,
      status: 'failed',
      durationMs: 0,
      error: 'Process-group cancellation is unsupported on this platform',
    };
  return new Promise((settle) => {
    const child = spawn(command.argv[0]!, command.argv.slice(1), {
      cwd: root,
      env: commandEnvironment(),
      shell: false,
      detached: true,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let stdout = Buffer.alloc(0),
      stderr = Buffer.alloc(0);
    let stdoutTruncated = false,
      stderrTruncated = false,
      timedOut = false,
      cancelled = false;
    let spawnError: string | undefined;
    const kill = () => {
      try {
        if (child.pid) process.kill(-child.pid, 'SIGKILL');
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== 'ESRCH') spawnError = 'Unable to terminate command process group';
      }
    };
    const abort = () => {
      cancelled = true;
      kill();
    };
    const timer = setTimeout(() => {
      timedOut = true;
      kill();
    }, command.timeoutMs ?? VERIFICATION_LIMITS.commandDefaultMs);
    signal.addEventListener('abort', abort, { once: true });
    child.once('spawn', () => {
      if (signal.aborted || cancelled) abort();
      else if (timedOut) kill();
    });
    child.stdout.on('data', (data: Buffer) => {
      stdoutTruncated ||= stdout.length + data.length > VERIFICATION_LIMITS.outputBytes;
      stdout = Buffer.concat([stdout, data.subarray(0, Math.max(0, VERIFICATION_LIMITS.outputBytes - stdout.length))]);
    });
    child.stderr.on('data', (data: Buffer) => {
      stderrTruncated ||= stderr.length + data.length > VERIFICATION_LIMITS.outputBytes;
      stderr = Buffer.concat([stderr, data.subarray(0, Math.max(0, VERIFICATION_LIMITS.outputBytes - stderr.length))]);
    });
    child.once('error', (error: NodeJS.ErrnoException) => {
      spawnError = `Command could not start (${error.code ?? 'unknown'})`;
    });
    child.once('close', (exitCode, exitSignal) => {
      clearTimeout(timer);
      signal.removeEventListener('abort', abort);
      settle({
        ...base,
        status: cancelled ? 'cancelled' : timedOut || spawnError || exitCode !== 0 ? 'failed' : 'passed',
        durationMs: performance.now() - started,
        exitCode,
        signal: exitSignal,
        timedOut,
        stdout: utf8(stdout),
        stderr: utf8(stderr),
        stdoutTruncated,
        stderrTruncated,
        ...(spawnError ? { error: spawnError } : {}),
      });
    });
    if (signal.aborted) abort();
  });
}

async function artifactCheck(
  root: string,
  artifact: { path: string; sha256?: string },
  signal: AbortSignal,
): Promise<VerificationCheck> {
  const started = performance.now();
  const base = { kind: 'artifact' as const, path: artifact.path };
  try {
    if (signal.aborted) throw new Error('Verification cancelled');
    const candidate = resolve(root, artifact.path);
    const rel = relative(root, candidate);
    if (isAbsolute(rel) || rel === '..' || rel.startsWith(`..${sep}`)) throw new Error('Artifact escapes project root');
    let current = root;
    for (const part of artifact.path.split('/')) {
      current = join(current, part);
      if ((await lstat(current)).isSymbolicLink()) throw new Error('Symlink artifacts are not allowed');
    }
    const before = await lstat(candidate);
    if (!before.isFile()) throw new Error('Artifact must be a regular file');
    if (before.size > VERIFICATION_LIMITS.artifactBytes) throw new Error('Artifact exceeds the 64MiB limit');
    if ((await realpath(candidate)) !== candidate) throw new Error('Symlink artifact components are not allowed');
    const handle = await open(
      candidate,
      constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0) | (constants.O_NONBLOCK ?? 0),
    );
    try {
      const info = await handle.stat();
      if (!info.isFile() || info.dev !== before.dev || info.ino !== before.ino)
        throw new Error('Artifact changed during open');
      const hash = createHash('sha256');
      const buffer = Buffer.alloc(64 * 1024);
      let bytes = 0;
      while (true) {
        if (signal.aborted) throw new Error('Verification cancelled');
        const read = await handle.read(buffer, 0, buffer.length, null);
        if (!read.bytesRead) break;
        bytes += read.bytesRead;
        if (bytes > VERIFICATION_LIMITS.artifactBytes) throw new Error('Artifact exceeds the 64MiB limit');
        hash.update(buffer.subarray(0, read.bytesRead));
      }
      const after = await handle.stat();
      const pathInfo = await lstat(candidate);
      if (
        info.size !== after.size ||
        info.mtimeMs !== after.mtimeMs ||
        pathInfo.isSymbolicLink() ||
        pathInfo.dev !== info.dev ||
        pathInfo.ino !== info.ino ||
        (await realpath(candidate)) !== candidate
      )
        throw new Error('Artifact changed during verification');
      const sha256 = hash.digest('hex');
      const passed = artifact.sha256 === undefined || artifact.sha256 === sha256;
      return {
        ...base,
        status: passed ? 'passed' : 'failed',
        durationMs: performance.now() - started,
        sha256,
        bytes,
        ...(passed ? {} : { error: 'Artifact SHA256 mismatch' }),
      };
    } finally {
      await handle.close();
    }
  } catch (error) {
    return {
      ...base,
      status: signal.aborted ? 'cancelled' : 'failed',
      durationMs: performance.now() - started,
      error: error instanceof Error ? error.message.slice(0, 512) : 'Artifact check failed',
    };
  }
}

export async function verifyAcceptance(input: VerificationInput): Promise<VerificationResult> {
  const started = performance.now();
  const spec = input.spec === undefined ? {} : validateAcceptance(input.spec);
  if (!(spec.commands?.length || spec.artifacts?.length)) return { status: 'unverified', checks: [], durationMs: 0 };
  const controller = new AbortController();
  const abort = () => controller.abort();
  let timedOut = false;
  const timer = setTimeout(() => {
    timedOut = true;
    abort();
  }, VERIFICATION_LIMITS.totalMs);
  input.signal?.addEventListener('abort', abort, { once: true });
  if (input.signal?.aborted) abort();
  const checks: VerificationCheck[] = [];
  try {
    const root = await realpath(input.root);
    for (const command of spec.commands ?? []) {
      checks.push(await commandCheck(root, command, controller.signal));
      if (controller.signal.aborted) break;
    }
    if (!controller.signal.aborted)
      for (const artifact of spec.artifacts ?? []) {
        checks.push(await artifactCheck(root, artifact, controller.signal));
        if (controller.signal.aborted) break;
      }
    return {
      status: input.signal?.aborted
        ? 'cancelled'
        : timedOut || checks.some((check) => check.status !== 'passed')
          ? 'failed'
          : 'passed',
      checks,
      durationMs: performance.now() - started,
      ...(timedOut ? { reason: 'Verification exceeded its 120-second global limit' } : {}),
    };
  } catch (error) {
    return {
      status: input.signal?.aborted ? 'cancelled' : 'failed',
      checks,
      durationMs: performance.now() - started,
      reason: error instanceof Error ? error.message.slice(0, 512) : 'Verification failed',
    };
  } finally {
    clearTimeout(timer);
    input.signal?.removeEventListener('abort', abort);
  }
}
